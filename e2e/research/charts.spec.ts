import { test, expect } from "@playwright/test";
import { sampleIndiaData } from "../../apps/frontend/src/features/research/india-summary.fixture";
test.use({ trace: "off" });
async function setup(context: import("@playwright/test").BrowserContext) {
  const state = await (await context.request.post("/api/v1/profiles/get_profile_state", {data:{}})).json();
  const grant = await (await context.request.post("/api/v1/profiles/unlock_profile", {data:{profileId:state.profiles[0].id}})).json();
  expect((await context.request.put("/api/v1/settings",{headers:{"x-wf-profile-scope":grant.scopeId},data:{onboardingCompleted:true,language:"en",baseCurrency:"INR",timezone:"Asia/Kolkata",syncEnabled:false,autoUpdateCheckEnabled:false}})).ok()).toBe(true);
}
test("Indian chart loads explicitly, polls visibly and unloads on close", async ({context,page},info)=>{
  await setup(context);
  const data=sampleIndiaData();let calls=0;
  await page.route("**/api/v1/research/india/connection",r=>r.fulfill({json:{configured:true,expiresOn:"2027-01-01"}}));
  await page.route("**/api/v1/research/india/search",r=>r.fulfill({json:{listings:[data.listing],retrievedAt:data.retrievedAt}}));
  await page.route("**/api/v1/research/india/chart",r=>{calls++;expect(r.request().postDataJSON()).toEqual({instrumentKey:data.listing.key,range:"month"});return r.fulfill({json:{listing:data.listing,range:"month",interval:"1 day",retrievedAt:"2026-10-27T00:00:00Z",quote:{price:12,lastTradeAt:"2026-10-23T10:00:00Z"},candles:[{time:"2026-10-22T00:00:00+05:30",open:10,high:12,low:9,close:11,volume:100},{time:"2026-10-23T00:00:00+05:30",open:11,high:13,low:10,close:12,volume:200}]}});});
  await page.setViewportSize({width:390,height:844});await page.goto("/research");
  await page.getByLabel("Market for stock research").selectOption("india");
  await page.getByLabel("Indian company name, symbol or ISIN").fill("TEST");
  await page.getByRole("button",{name:"Search India",exact:true}).click();
  await page.getByLabel("Verified company listing").selectOption(data.listing.key);
  expect(calls).toBe(0);
  await page.getByRole("button",{name:"Open chart",exact:true}).click();
  await expect(page.getByRole("group",{name:"Candle closing-price history in INR"})).toBeVisible();
  expect(calls).toBe(1);
  await page.clock.install({time:new Date("2026-10-27T00:00:00Z")});
  await page.getByLabel("Update every 15 seconds").check();
  await page.clock.runFor(15100);
  await expect.poll(()=>calls).toBe(2);
  await page.getByRole("group",{name:"Candle closing-price history in INR"}).scrollIntoViewIfNeeded();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:info.outputPath("india-chart-mobile.png")});
  await page.getByRole("button",{name:"Close chart",exact:true}).click();
  await page.clock.runFor(16000);expect(calls).toBe(2);
  await expect(page.getByRole("group",{name:"Candle closing-price history in INR"})).toHaveCount(0);
});
test("US delayed chart renders in its restricted provider frame",async({context,page},info)=>{
  test.skip(process.env.WF_RESEARCH_LIVE_TEST!=="1","Explicit public-source opt-in required");
  await setup(context);await page.setViewportSize({width:1280,height:900});await page.goto("/research");
  await page.getByLabel("US ticker or SEC company ID").fill("MSFT");
  await page.getByRole("button",{name:"Analyse",exact:true}).click();
  await expect(page.getByRole("heading",{name:/Microsoft|MICROSOFT/})).toBeVisible({timeout:60000});
  await expect(page.locator("iframe")).toHaveCount(0);
  await page.getByLabel("Chart exchange").selectOption("NASDAQ");
  await page.getByRole("button",{name:"Open chart",exact:true}).click();
  const frame=page.getByTitle("NASDAQ:MSFT TradingView chart");
  await expect(frame).toBeVisible();
  await frame.scrollIntoViewIfNeeded();
  await expect(page.frameLocator('iframe[title="NASDAQ:MSFT TradingView chart"]').locator("canvas").first()).toBeVisible({timeout:45000});
  await expect.poll(async()=>/\b[1-9]\d{1,4}[.,]\d{2}\b/.test(await page.frameLocator('iframe[title="NASDAQ:MSFT TradingView chart"]').locator("body").innerText()),{timeout:45000,message:"Wait for a nonzero displayed price, not just a placeholder canvas"}).toBe(true);
  await page.screenshot({path:info.outputPath("us-chart-desktop.png")});
  await page.getByRole("button",{name:"Close chart",exact:true}).click();await expect(frame).toHaveCount(0);
  await page.setViewportSize({width:390,height:844});
  await page.getByLabel("US ticker or SEC company ID").fill("MSFT");
  await page.getByRole("button",{name:"Analyse",exact:true}).click();
  await expect(page.getByRole("heading",{name:/Microsoft|MICROSOFT/})).toBeVisible({timeout:60000});
  await page.getByLabel("Chart exchange").selectOption("NASDAQ");
  await page.getByRole("button",{name:"Open chart",exact:true}).click();
  await frame.scrollIntoViewIfNeeded();
  await expect(page.frameLocator('iframe[title="NASDAQ:MSFT TradingView chart"]').locator("canvas").first()).toBeVisible({timeout:45000});
  await expect.poll(async()=>/\b[1-9]\d{1,4}[.,]\d{2}\b/.test(await page.frameLocator('iframe[title="NASDAQ:MSFT TradingView chart"]').locator("body").innerText()),{timeout:45000,message:"Wait for actual mobile price data"}).toBe(true);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:info.outputPath("us-chart-mobile.png")});
});
